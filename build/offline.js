import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

// The whole app is static, so a build-time precache list makes every tool work
// offline after the first visit. `staticFiles` covers public/ assets the bundle
// does not list; runtime fetches are cached as used.
export function offlinePlugin(base, staticFiles = []) {
  let publicDir = 'public'

  return {
    name: 'convbin-offline',
    apply: 'build',
    configResolved(config) {
      publicDir = config.publicDir
    },
    generateBundle: {
      // Vite writes index.html in its own generateBundle, so run after it to
      // include the page in the cache version.
      order: 'post',
      handler(_options, bundle) {
        const built = Object.keys(bundle).filter((file) => !file.endsWith('.map'))
        const index = bundle['index.html']
        const revision = createHash('sha256')
          .update(String(index?.type === 'asset' ? index.source : ''))
        // Hash public files too: same name, new content must still update the cache.
        for (const file of staticFiles) revision.update(readFileSync(join(publicDir, file)))

        this.emitFile({
          type: 'asset',
          fileName: 'sw.js',
          source: serviceWorkerSource(
            [...staticFiles, ...built],
            base,
            revision.digest('hex'),
          ),
        })
      },
    },
  }
}

export function serviceWorkerSource(files, base, revision = '') {
  const urls = [...new Set(['', 'index.html', ...files])].map((file) => base + file)
  const version = createHash('sha256').update(urls.join('\n') + revision).digest('hex').slice(0, 12)

  return `// Generated by build/offline.js at build time. Do not edit.
const CACHE = 'convbin-${version}'
const INDEX = ${JSON.stringify(base + 'index.html')}
const PRECACHE = ${JSON.stringify(urls, null, 2)}

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      // shortcut: a tab left open across a deploy can miss chunks it never loaded
      .then(() => self.skipWaiting()),
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys.filter((key) => key.startsWith('convbin-') && key !== CACHE).map((key) => caches.delete(key)),
      ))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const { request } = event
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached
      return fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone()
            event.waitUntil(
              caches.open(CACHE).then((cache) => cache.put(request, copy)).catch(() => {}),
            )
          }
          return response
        })
        .catch(() => (request.mode === 'navigate'
          ? caches.match(INDEX).then((index) => index || Response.error())
          : Response.error()))
    }),
  )
})
`
}
