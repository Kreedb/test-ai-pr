// Regression tests for the PADS Layout ASCII -> Circuit JSON -> KiCad path.
// Run with `npm test` (node:test, no extra dependencies).

import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import test from 'node:test'
import { fileURLToPath } from 'node:url'

import { convertEda, detectSource } from '../src/lib/eda.js'
import { looksLikePadsAscii, padsToCircuitJson, parsePadsAscii } from '../src/lib/pads.js'

const root = fileURLToPath(new URL('..', import.meta.url))
const read = (name) => readFileSync(join(root, 'public/samples/pads', name), 'utf8')
const sample = (name) => new Uint8Array(readFileSync(join(root, 'public/samples/pads', name)))

// Fixtures from tscircuit/padsts (MIT) cover the format corners the sample board
// does not: layered vias, thermal vias, copper cutouts and decal text.
const upstream = (name) => readFileSync(join(root, 'test/fixtures/pads', name), 'utf8')

const kicad = await import('kicadts')

function findBlock(source, start, keyword) {
  const index = source.indexOf(keyword, start)
  if (index < 0) return null
  let depth = 0
  for (let cursor = index; cursor < source.length; cursor += 1) {
    if (source[cursor] === '(') depth += 1
    else if (source[cursor] === ')') {
      depth -= 1
      if (depth === 0) return source.slice(index, cursor + 1)
    }
  }
  return source.slice(index)
}

function padFor(pcb, reference, padNumber) {
  let cursor = 0
  let block = null
  while ((block = findBlock(pcb, cursor, '(footprint')) !== null) {
    if (!block.includes(`(property "Reference" "${reference}"`)) {
      cursor = pcb.indexOf('(footprint', cursor) + 1
      if (cursor <= 0) return null
      continue
    }
    const pad = findBlock(block, 0, `(pad "${padNumber}"`)
    if (pad) return pad
    cursor = pcb.indexOf('(footprint', cursor) + 1
    if (cursor <= 0) return null
  }
  return null
}

test('detects PADS ASCII instead of treating .asc as unknown', () => {
  assert.equal(looksLikePadsAscii(read('res0805.asc')), true)
  assert.equal(detectSource('board.asc', sample('res0805.asc')).id, 'pads')
  assert.equal(detectSource('board.asc', sample('res0805.asc')).kind, 'pcb')

  // A netlist that happens to use the same extension must not be read as PADS.
  const other = new Uint8Array(Buffer.from('* Netlist generated by some tool\n'))
  assert.equal(detectSource('netlist.asc', other).id, 'unknown')
  assert.equal(looksLikePadsAscii('<html></html>'), false)
})

test('parses the PADS header, units and layer count', () => {
  const parsed = parsePadsAscii(read('res0805.asc'))
  assert.equal(parsed.version, 'V9.5')
  assert.equal(parsed.units, 'MILS')
  assert.equal(parsed.layerCount, 2)
  assert.ok(Math.abs(parsed.scale - 0.0254) < 1e-12)

  // `UNITS 0` in the PCB section restates mils; the header suffix decides.
  const minimal = parsePadsAscii(upstream('minimal.asc'))
  assert.equal(minimal.units, 'BASIC')
  assert.equal(parsePadsAscii(upstream('text-layers.asc')).units, 'MILS')
})

test('converts a PADS ASCII board into a KiCad project', async () => {
  const result = await convertEda([{ name: 'res0805.asc', bytes: sample('res0805.asc') }])

  assert.equal(result.source, 'pads')
  assert.equal(result.summary.hasBoard, true)
  assert.equal(result.summary.board.components, 3)
  assert.equal(result.summary.board.nets, 3)
  assert.equal(result.summary.board.vias, 1)
  assert.equal(result.summary.board.tracks, 6)
  // R1/R2 are two-terminal 0805s and J1 is a three-pin header: 4 SMD pads plus
  // three drilled pads, two of which are round and one square.
  assert.equal(result.summary.board.pads, 7)
  assert.equal(result.summary.models, 0)

  const names = result.files.map((file) => file.name)
  assert.deepEqual(names, ['res0805.kicad_pcb'])

  const pcb = result.files[0].content
  assert.doesNotThrow(() => kicad.parseKicadPcb(pcb))
  assert.ok(pcb.includes('"PADS ASCII DEMO"'), 'board silkscreen text should survive')
})

test('mirrored parts put their pads on the back and swap the pad order', async () => {
  const result = await convertEda([{ name: 'res0805.asc', bytes: sample('res0805.asc') }])
  const pcb = result.files[0].content

  const top = findBlock(pcb, 0, '(footprint')
  assert.ok(top, 'expected at least one footprint')

  // PADS R2 has mirror `M`, so the footprint lands on B.Cu and pad 1 sits to the
  // right of the part (mirror negates the decal-local x before rotating).
  let cursor = 0
  let mirrored = null
  let block = null
  while ((block = findBlock(pcb, cursor, '(footprint')) !== null) {
    if (block.includes('(property "Reference" "R2"')) {
      mirrored = block
      break
    }
    cursor = pcb.indexOf('(footprint', cursor) + 1
    if (cursor <= 0) break
  }
  assert.ok(mirrored, 'expected the mirrored R2 footprint')
  assert.ok(mirrored.includes('(layer B.Cu)'), 'mirrored part should land on the back copper')

  const firstPad = findBlock(mirrored, 0, '(pad "1"')
  const secondPad = findBlock(mirrored, 0, '(pad "2"')
  assert.ok(firstPad && secondPad)
  const xOf = (block) => Number(/\(at ([\d.eE+-]+) /.exec(block)?.[1])
  // Decal pad 1 is at local x = -45 mil, pad 2 at +45 mil; mirroring swaps them.
  assert.ok(xOf(firstPad) > 0, `mirrored pad 1 should sit at positive local x, got ${firstPad}`)
  assert.ok(xOf(secondPad) < 0, `mirrored pad 2 should sit at negative local x, got ${secondPad}`)
})

test('nets, traces and vias keep their layer and net', async () => {
  const result = await convertEda([{ name: 'res0805.asc', bytes: sample('res0805.asc') }])
  const pcb = result.files[0].content

  const via = findBlock(pcb, 0, '(via')
  assert.ok(via, 'expected one routed via')
  assert.ok(via.includes('0.635'), `via drill should come from the VIA definition: ${via}`)

  const gnd = padFor(pcb, 'J1', '2')
  assert.ok(gnd?.includes('"GND"'), `J1 pad 2 should keep its net: ${gnd}`)
  const vcc = padFor(pcb, 'J1', '1')
  assert.ok(vcc?.includes('"VCC"'), `J1 pad 1 should keep its net: ${vcc}`)
  // J1.2 is a square through-hole pad.
  assert.ok(gnd.includes('rect'), 'square drilled pad should be a rectangular pad')
})

test('upstream fixtures convert without throwing', () => {
  // The pads-to-circuit-json suite expects 8 pads and one via for these.
  // The board declares four copper layers, so the through via spans all of them,
  // the blind via only the two inner ones, and the override restates 1..4.
  const layered = parsePadsAscii(upstream('layered-vias.asc'))
  const viaElements = padsToCircuitJson(layered).filter((element) => element.type === 'pcb_via')
  assert.equal(viaElements.length, 3)
  assert.deepEqual(
    viaElements.map((via) => via.layers),
    [
      ['top', 'inner1', 'inner2', 'bottom'],
      ['inner1', 'inner2'],
      ['top', 'inner1', 'inner2', 'bottom'],
    ],
  )

  const drilled = padsToCircuitJson(parsePadsAscii(upstream('drilled-decals.asc')))
  assert.equal(drilled.filter((element) => element.type === 'pcb_plated_hole').length, 4)
  assert.equal(drilled.filter((element) => element.type === 'pcb_hole').length, 4)
  assert.equal(drilled.filter((element) => element.type === 'pcb_smtpad').length, 4)

  const placed = padsToCircuitJson(parsePadsAscii(upstream('placed-decals.asc')))
  assert.equal(placed.filter((element) => element.type === 'pcb_smtpad').length, 8)
  assert.equal(placed.filter((element) => element.type === 'pcb_component').length, 2)

  // Copper cutouts and thermal vias must not throw even though the pour and
  // relief geometry is simplified.
  for (const name of ['copper-cutouts.asc', 'thermal-vias.asc', 'decal-graphics.asc', 'decal-text.asc', 'text-layers.asc']) {
    assert.doesNotThrow(() => padsToCircuitJson(parsePadsAscii(upstream(name))), `${name} should convert`)
  }

  // Thermal (RT/ST), antipad (RA/SA) and annular (A) rows are clearance
  // geometry, so the finished via keeps its barrel size (40/44 mil), not the
  // relief outline.
  const thermal = padsToCircuitJson(parsePadsAscii(upstream('thermal-vias.asc'))).filter(
    (element) => element.type === 'pcb_via',
  )
  assert.deepEqual(
    thermal.map((via) => Number(via.outer_diameter.toFixed(4))),
    [1.016, 1.1176],
  )
  assert.deepEqual(thermal.map((via) => via.hole_diameter), [0.508, 0.508])
})

test('route points from different nets never get joined', () => {
  // Two nets routed on the same layer, one after the other, with no via between
  // them. A naive "previous point per layer" join would bridge A into B.
  const source = `!PADS-POWERPCB-V9.5-MILS! x
*PCB*
MAXIMUMLAYER 2
*ROUTE*
*SIGNAL* A
0 0 1 10
100 0 1 10
*SIGNAL* B
0 100 1 10
100 100 1 10
*LINES*
BOARD_OUTLINE BOARD 0 0 1 0
CLOSED 5 0 0
-50 -50
150 -50
150 150
-50 150
-50 -50
*END*
`
  const traces = padsToCircuitJson(parsePadsAscii(source)).filter(
    (element) => element.type === 'pcb_trace',
  )
  assert.equal(traces.length, 2)
  const ys = traces.map((trace) => trace.route.map((point) => point.y).join(','))
  assert.deepEqual(ys, ['0,0', '2.54,2.54'])
})

test('rejects a non-PADS .asc through the conversion entry point', async () => {
  const bytes = new Uint8Array(Buffer.from('* Netlist generated by some tool\n'))
  await assert.rejects(() => convertEda([{ name: 'netlist.asc', bytes }]), /无法识别|PADS/)
})
